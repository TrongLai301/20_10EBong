-- 1. Tạo bảng replies
create table if not exists public.replies (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  choice text not null,               -- 'yes', 'no_then_yes', hoặc 'no'
  message text not null,              -- Lời nhắn của cô ấy
  sender_name text default 'Bí mật',  -- Biệt danh / Tên người gửi
  device_info text                    -- Thiết bị / Trình duyệt
);

-- 2. Bật tính năng Row Level Security (RLS)
alter table public.replies enable row level security;

-- 3. Tạo chính sách (Policy) cho phép người nhận (ẩn danh/public) có thể gửi lời nhắn
drop policy if exists "Cho phép gửi phản hồi ẩn danh" on public.replies;
create policy "Cho phép gửi phản hồi ẩn danh"
  on public.replies
  for insert
  to anon, authenticated
  with check (true);

-- 4. Tạo chính sách chỉ cho phép bạn (chủ sở hữu) xem các tin nhắn đã gửi
drop policy if exists "Chỉ chủ sở hữu đọc được tin nhắn" on public.replies;
create policy "Chỉ chủ sở hữu đọc được tin nhắn"
  on public.replies
  for select
  to authenticated
  using (true);
